// Writes src/ui/tahoma-bold-metrics.ts
// from tahomabd.ttf (hmtx advance, glyf bbox) plus the QtSvg lead corrections
// (glyphs whose drawn ink starts left of their outline box at some face size).
import fs from "node:fs";
import { loadFont } from "./lib/ttf.mjs";
const [fontPath, correctionsPath, outPath] = process.argv.slice(2);
const f = loadFont(fontPath);
const corrections = JSON.parse(fs.readFileSync(correctionsPath, "utf8"));
const BLOCKS = [[0x20, 0x7e], [0xa0, 0xff], [0x100, 0x17f], [0x180, 0x24f], [0x370, 0x3ff], [0x400, 0x4ff], [0x500, 0x52f], [0x1e00, 0x1eff], [0x2000, 0x206f], [0x2070, 0x209f], [0x20a0, 0x20cf], [0x2100, 0x214f], [0x2150, 0x218f], [0x2190, 0x21ff], [0x2200, 0x22ff], [0x25a0, 0x25ff]];
// Format controls QtSvg draws at no advance (measured): never priced as glyphs.
const control = (cp) => cp === 0xad || (cp >= 0x200b && cp <= 0x200f) || (cp >= 0x2028 && cp <= 0x202e) || (cp >= 0x2060 && cp <= 0x206f);
const lines = [];
let count = 0;
for (const [a, b] of BLOCKS) {
	const nums = [];
	for (let cp = a; cp <= b; cp++) {
		const ch = String.fromCodePoint(cp);
		const m = f.metrics(ch);
		if (!m || m.a === 0 || control(cp)) { nums.push(0, 0, 0); continue; }
		count++;
		if (m.empty) { nums.push(-m.a, 0, 0); continue; }
		nums.push(m.a, m.lsb - (corrections[ch]?.[0] ?? 0), m.rsb - (corrections[ch]?.[1] ?? 0));
	}
	while (nums.length >= 3 && nums[nums.length - 3] === 0) nums.splice(-3);
	lines.push(`\t[0x${a.toString(16).padStart(4, "0")}, [${nums.join(",")}]]`);
}
const out = `/**
 * Tahoma Bold glyph metrics, generated by scripts/gen-tahoma-metrics.mjs from
 * tahomabd.ttf; do not edit by hand. Per block: the first code point, then
 * three numbers per code point in font units (2048 per em): the advance (hmtx,
 * which the app's QtSvg 6.9.3 draws to within 0.02 px at the 12 px basis),
 * the lead and the trail (the outline box's distance inside the advance at
 * each end, from glyf), each reduced where the app's QtSvg drew ink closer
 * to that end than the edge rules in format.ts allow (${Object.keys(corrections).length} glyphs, probes
 * 2026-10-09). A blank glyph
 * (a space) is written with its advance negated and no ink; an unassigned
 * code point is 0,0,0.
 * ${count} glyphs: Basic Latin, Latin-1 Supplement, Latin Extended-A and -B,
 * Greek, Cyrillic and its supplement, Latin Extended Additional, General
 * Punctuation, super- and subscripts, currency, letterlike symbols, number
 * forms, arrows, mathematical operators and geometric shapes.
 */
export const TAHOMA_BOLD_UNITS_PER_EM = 2048;
export const TAHOMA_BOLD_BLOCKS: ReadonlyArray<readonly [number, readonly number[]]> = [
${lines.join(",\n")}
];
`;
fs.writeFileSync(outPath, out);
console.log("glyphs", count, "bytes", out.length);
