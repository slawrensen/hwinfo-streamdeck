// The two files `npm run l10n` writes from the string catalog
// (src/i18n-catalog.ts), built as strings so test/i18n.test.ts can hold
// the committed files to them byte for byte:
//
//   com.lawrensen.hwinfo.sdPlugin/en.json  the Stream Deck SDK's language
//     file: the manifest's user-facing strings (root Name and Description,
//     each action's Name, Tooltip and Encoder TriggerDescription), copied
//     from manifest.json because a language file overrides the manifest in
//     that language, plus the Localization block (the runtime catalog, EN)
//     that the plugin's t() reads through streamDeck.i18n.
//   com.lawrensen.hwinfo.sdPlugin/ui/pi-strings.js  the panel catalog
//     (PANEL) and hwT().

/** The manifest fields a language file copies. */
export type ManifestText = {
	Name: string;
	Description: string;
	Actions?: ReadonlyArray<{ UUID: string; Name: string; Tooltip: string; Encoder?: { TriggerDescription?: Readonly<Record<string, string>> } }>;
};
type ActionText = { Name: string; Tooltip: string; Encoder?: { TriggerDescription: Record<string, string> } };

/** The manifest strings a language file carries, in manifest order. */
export function manifestStrings(manifest: ManifestText): Record<string, string | ActionText> {
	const out: Record<string, string | ActionText> = { Name: manifest.Name, Description: manifest.Description };
	for (const action of manifest.Actions ?? []) {
		const entry: ActionText = { Name: action.Name, Tooltip: action.Tooltip };
		if (action.Encoder?.TriggerDescription !== undefined) entry.Encoder = { TriggerDescription: { ...action.Encoder.TriggerDescription } };
		out[action.UUID] = entry;
	}
	return out;
}

/** en.json: the manifest strings plus the Localization block. */
export function enJson(manifest: ManifestText, catalog: object): string {
	return `${JSON.stringify({ ...manifestStrings(manifest), Localization: catalog }, null, "\t")}\n`;
}

const indent = (text: string, tabs: number): string => text.split("\n").map((line, i) => (i === 0 ? line : "\t".repeat(tabs) + line)).join("\n");

/** ui/pi-strings.js: the panel's catalog and its lookup. */
export function piStringsJs(panel: { readonly pi: object }): string {
	const table = indent(JSON.stringify(panel, null, "\t"), 2);
	return `/* GENERATED by \`npm run l10n\` from src/i18n-catalog.ts: edit the catalog,
   then run it. test/i18n.test.ts fails when this file and the catalog
   disagree.

   The settings panels' string catalog, loaded before pi-shell.js.
   English only in 1.8.0 (docs/localization.md).

   hwT(key, english, params) answers the panel's language, then English,
   then the English passed in, then the key; each {name} takes params.name.
   Panel scripts call it for the strings they build.

   Markup: an element with data-l10n="key" takes the string as its leading
   text (the text before its first child element; leading and trailing
   spaces are kept), and data-l10n-placeholder, data-l10n-aria-label and
   data-l10n-title set those attributes. The English stays in the markup,
   so in English nothing is rewritten and the page is the file as written.

   The language is the webview's navigator.language mapped the way
   sdpi-components maps it; one with no catalog here reads English.
   Numbers keep the '.' decimal separator in every language.
   window.hwPiLocale ({ language, strings }), set before this script runs,
   adds a catalog and selects it: the panel expansion test
   (scripts/e2e-pi-l10n.mjs) uses it for its pseudo-locale. */
(() => {
	"use strict";

	const locales = {
		en: ${table}
	};

	/** Stream Deck's language code for a browser language tag. */
	function streamDeckLanguage(tag) {
		if (typeof tag !== "string" || tag === "") return "en";
		if (tag === "zh-Hant" || tag === "zh-TW") return "zh_TW";
		if (tag === "zh" || tag === "zh-Hans" || tag === "zh-CN") return "zh_CN";
		return tag.split("-")[0];
	}

	const given = window.hwPiLocale;
	const injected = given !== null && typeof given === "object" && typeof given.language === "string" && given.strings !== null && typeof given.strings === "object";
	if (injected) locales[given.language] = given.strings;
	const wanted = injected ? given.language : streamDeckLanguage(navigator.language);
	const language = Object.hasOwn(locales, wanted) ? wanted : "en";

	function lookup(table, key) {
		let node = table;
		for (const part of key.split(".")) {
			if (node === null || typeof node !== "object" || !Object.hasOwn(node, part)) return undefined;
			node = node[part];
		}
		return typeof node === "string" && node !== "" ? node : undefined;
	}

	function hwT(key, english, params) {
		const text = lookup(locales[language], key) ?? lookup(locales.en, key) ?? english ?? key;
		return params === undefined ? text : text.replace(/\\{(\\w+)\\}/g, (whole, name) => (Object.hasOwn(params, name) ? String(params[name]) : whole));
	}

	const ATTRIBUTES = [
		["data-l10n-placeholder", "placeholder"],
		["data-l10n-aria-label", "aria-label"],
		["data-l10n-title", "title"]
	];

	/** Puts the panel's language into the marked elements under root. A
	 * no-op in English: the markup already is the English. */
	function hwApplyStrings(root) {
		if (language === "en") return;
		for (const el of root.querySelectorAll("[data-l10n]")) {
			const text = lookup(locales[language], el.dataset.l10n);
			const node = el.firstChild;
			if (text === undefined || node === null || node.nodeType !== Node.TEXT_NODE) continue;
			const lead = /^\\s*/.exec(node.data)[0];
			const trail = /\\s*$/.exec(node.data.slice(lead.length))[0];
			node.data = lead + text + trail;
		}
		for (const [data, attribute] of ATTRIBUTES) {
			for (const el of root.querySelectorAll(\`[\${data}]\`)) {
				const text = lookup(locales[language], el.getAttribute(data));
				if (text !== undefined) el.setAttribute(attribute, text);
			}
		}
	}

	window.hwT = hwT;
	window.hwApplyStrings = hwApplyStrings;
	window.hwPiLanguage = language;
	hwApplyStrings(document);
})();
`;
}
