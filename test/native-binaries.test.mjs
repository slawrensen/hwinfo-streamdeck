// The shared list of shipped native binaries (scripts/lib/native-binaries.mjs)
// is what the source-id generator, the vendoring step, the packaging gate,
// the manifest and the pack contract all read. Pure checks over the tree
// and synthetic bytes; no native build needed.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import { NATIVE_BINARIES, TEST_ONLY_NATIVE_FILES, TEST_ONLY_NATIVE_PATTERN, nativeContract, nativeSourceId, sourceIdHeader, versionResourceString } from "../scripts/lib/native-binaries.mjs";
import { candidateNativeContract } from "../scripts/lib/soak-producer-freshness.mjs";
import { SHIPPED_MEMBERS } from "../scripts/lib/pack-contract.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));

/** One StringFileInfo String structure as rc.exe lays it out. */
function stringEntry(key, value, { terminate = true } = {}) {
	const keyBytes = Buffer.from(`${key}\0`, "utf16le");
	const valueText = terminate ? `${value}\0` : value;
	const headerAndKey = 6 + keyBytes.length;
	const padded = Math.ceil(headerAndKey / 4) * 4;
	const valueBytes = Buffer.from(valueText, "utf16le");
	const out = Buffer.alloc(padded + valueBytes.length);
	out.writeUInt16LE(out.length, 0);
	out.writeUInt16LE(valueText.length, 2);
	out.writeUInt16LE(1, 4);
	keyBytes.copy(out, 6);
	valueBytes.copy(out, padded);
	return out;
}

describe("native binary list", () => {
	it("names the shipped binary, a pack member, and its test-only builds", () => {
		assert.deepEqual(NATIVE_BINARIES.map((binary) => binary.file), ["hwsm.node"]);
		for (const binary of NATIVE_BINARIES) assert.ok(SHIPPED_MEMBERS.includes(`bin/${binary.file}`), binary.file);
		assert.deepEqual([...TEST_ONLY_NATIVE_FILES], ["hwsm_test.node", "hwsm_protomm.node"]);
		for (const file of TEST_ONLY_NATIVE_FILES) assert.match(file, TEST_ONLY_NATIVE_PATTERN);
		for (const binary of NATIVE_BINARIES) assert.doesNotMatch(binary.file, TEST_ONLY_NATIVE_PATTERN);
	});

	it("keeps hwsm's source id exactly as the soak's candidate contract computes it", () => {
		const hwsm = NATIVE_BINARIES[0];
		assert.equal(nativeSourceId(ROOT, hwsm), candidateNativeContract(ROOT).nativeSourceId);
		assert.deepEqual(nativeContract(ROOT, hwsm), (({ protocolVersion, napiVersion, nativeVersion, nativeSourceId: id }) => ({ protocolVersion, napiVersion, nativeVersion, nativeSourceId: id }))(candidateNativeContract(ROOT)));
	});

	it("writes hwsm's generated header byte for byte", () => {
		assert.equal(sourceIdHeader(NATIVE_BINARIES[0], "0123456789abcdef"), "/* Generated by scripts/native-source-id.mjs; do not edit or commit. */\n#define HWSM_SOURCE_ID \"0123456789abcdef\"\n");
	});

	it("refuses a contract whose two protocol numbers disagree", () => {
		const root = fs.mkdtempSync(path.join(os.tmpdir(), "hwinfo-native-contract-"));
		try {
			const binary = NATIVE_BINARIES[0];
			for (const rel of [...binary.sources.map((name) => `${binary.dir}/${name}`), binary.contract.path]) {
				fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
				fs.copyFileSync(path.join(ROOT, rel), path.join(root, rel));
			}
			const contractFile = path.join(root, binary.contract.path);
			fs.writeFileSync(contractFile, fs.readFileSync(contractFile, "utf8").replace("export const HWSM_PROTOCOL_VERSION = 1;", "export const HWSM_PROTOCOL_VERSION = 2;"));
			assert.throws(() => nativeContract(root, binary), /two protocol versions must be the same/);
		} finally {
			fs.rmSync(root, { recursive: true, force: true });
		}
	});
});

describe("version resource string reader", () => {
	it("reads a value by key with or without rc.exe's terminating NUL, at any alignment", () => {
		for (const terminate of [true, false]) {
			for (const lead of [0, 2, 6]) {
				const bytes = Buffer.concat([Buffer.alloc(lead), stringEntry("OriginalFilename", "hwsm.node", { terminate }), stringEntry("SourceId", "9eb8336ed3ab89ee", { terminate }), stringEntry("LegalCopyright", "MIT", { terminate })]);
				assert.equal(versionResourceString(bytes, "SourceId"), "9eb8336ed3ab89ee", `terminate=${terminate} lead=${lead}`);
				assert.equal(versionResourceString(bytes, "OriginalFilename"), "hwsm.node");
			}
		}
	});

	it("returns null for an absent key and for a structure that does not hold together", () => {
		const good = stringEntry("SourceId", "9eb8336ed3ab89ee");
		assert.equal(versionResourceString(good, "Comments"), null);
		const wrongType = Buffer.from(good);
		wrongType.writeUInt16LE(0, 4);
		assert.equal(versionResourceString(wrongType, "SourceId"), null);
		const overlong = Buffer.from(good);
		overlong.writeUInt16LE(4000, 2);
		assert.equal(versionResourceString(overlong, "SourceId"), null);
		assert.equal(versionResourceString(good.subarray(4), "SourceId"), null, "the header before the key is missing");
	});
});
