// The toolchain record (scripts/lib/native-toolchain.mjs) is the evidence a
// drift report rests on, so its parsing, path normalization, digests and
// policy comparison are pinned here over synthetic build trees: MSBuild
// tracking logs in both encodings MSBuild writes, a fake MSVC and Windows
// Kits layout, a fake node-gyp header cache. No native build needed; the
// record of a real build is checked by test/native-manifest.test.ts.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import { NATIVE_BINARIES } from "../scripts/lib/native-binaries.mjs";
import { POLICY_FIELD_NAMES, binaryInputs, collectToolchain, comparePolicy, configGypiValue, decodeTlogText, digestLines, fileVersionOf, inputsDigestOf, makeRoots, normalizeCommand, normalizePath, parseLastBuildState, readTlogCommands, readTlogEntries, sdkServicingFrom } from "../scripts/lib/native-toolchain.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const utf16 = (text) => Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(text, "utf16le")]);
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "hwinfo-toolchain-"));
after(() => fs.rmSync(scratch, { recursive: true, force: true }));

describe("tracking log parsing", () => {
	it("decodes UTF-16LE with its BOM, UTF-8, and UTF-16LE without a BOM", () => {
		assert.equal(decodeTlogText(utf16("^A\r\nB\r\n")), "^A\r\nB\r\n");
		assert.equal(decodeTlogText(Buffer.from("PlatformToolSet=v143:\r\n", "utf8")), "PlatformToolSet=v143:\r\n");
		assert.equal(decodeTlogText(Buffer.from("C:\\X", "utf16le")), "C:\\X");
		assert.equal(decodeTlogText(Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from("x")])), "x");
	});

	it("reads read-log entries without the ^source headers, upper-cased and de-duplicated", () => {
		const log = utf16("^C:\\REPO\\NATIVE\\HWSM\\HWSM.C\r\nC:\\Kits\\10\\Include\\um\\windows.h\r\nC:\\KITS\\10\\INCLUDE\\UM\\WINDOWS.H\r\n^C:\\REPO\\B.CC\r\nC:\\KITS\\10\\LIB\\UM\\X64\\KERNEL32.LIB\r\n\r\n");
		assert.deepEqual(readTlogEntries(log), ["C:\\KITS\\10\\INCLUDE\\UM\\WINDOWS.H", "C:\\KITS\\10\\LIB\\UM\\X64\\KERNEL32.LIB"]);
	});

	it("joins link's response-file lines into the command they belong to", () => {
		const log = utf16("^C:\\R\\A.OBJ|C:\\R\\B.RES\r\n/OUT:\"C:\\R\\X.NODE\" /DLL RELEASE\\B.RES\r\nRELEASE\\A.OBJ\r\n");
		assert.deepEqual(readTlogCommands(log), [{ sources: ["C:\\R\\A.OBJ", "C:\\R\\B.RES"], command: "/OUT:\"C:\\R\\X.NODE\" /DLL RELEASE\\B.RES RELEASE\\A.OBJ" }]);
	});

	it("reads the build state and node-gyp's config", () => {
		assert.deepEqual(parseLastBuildState("PlatformToolSet=v143:VCToolArchitecture=Native64Bit:VCToolsVersion=14.51.36231:TargetPlatformVersion=10.0.26100.0:\r\nRelease|x64|D:\\a\\repo\\native\\hwsm\\build\\|\r\n"), { platformToolset: "v143", toolArchitecture: "Native64Bit", toolsVersion: "14.51.36231", targetPlatformVersion: "10.0.26100.0" });
		assert.deepEqual(parseLastBuildState(""), { platformToolset: null, toolArchitecture: null, toolsVersion: null, targetPlatformVersion: null });
		const gypi = "# Do not edit. Generated by the configure script.\n{ \"variables\": { \"nodedir\": \"C:\\\\Users\\\\runneradmin\\\\AppData\\\\Local\\\\node-gyp\\\\Cache\\\\20.20.0\", \"msbuild_toolset\": \"v143\" } }\n";
		assert.equal(configGypiValue(gypi, "nodedir"), "C:\\Users\\runneradmin\\AppData\\Local\\node-gyp\\Cache\\20.20.0");
		assert.equal(configGypiValue(gypi, "msbuild_toolset"), "v143");
		assert.equal(configGypiValue(gypi, "absent"), null);
	});

	it("reads a FileVersion from VS_FIXEDFILEINFO and the SDK servicing build from the uninstall registration", () => {
		const info = Buffer.alloc(64);
		info.writeUInt32LE(0xfeef04bd, 16);
		info.writeUInt32LE((19 << 16) | 51, 24);
		info.writeUInt32LE((36260 << 16) >>> 0, 28);
		assert.equal(fileVersionOf(info), "19.51.36260.0");
		assert.equal(fileVersionOf(Buffer.alloc(64)), null);
		const reg = "HKEY_LOCAL_MACHINE\\...\\{a}\r\n    DisplayName    REG_SZ    Windows Software Development Kit - Windows 10.0.19041.5609\r\nHKEY_LOCAL_MACHINE\\...\\{b}\r\n    DisplayName    REG_SZ    Windows Software Development Kit - Windows 10.0.26100.4188\r\n    DisplayName    REG_SZ    Windows Software Development Kit - Windows 10.0.26100.7705\r\n";
		assert.equal(sdkServicingFrom(reg, "10.0.26100.0"), "10.0.26100.7705");
		assert.equal(sdkServicingFrom(reg, "10.0.22621.0"), null);
	});
});

describe("path normalization and digests", () => {
	const roots = makeRoots({ "<msvc>": "C:\\VS\\VC\\Tools\\MSVC\\14.51.36231", "<vs>": "C:\\VS", "<kits>": "C:\\Program Files (x86)\\Windows Kits\\10", "<node_modules>": "D:\\a\\repo\\node_modules", "<repo>": "D:\\a\\repo", "<nodedir>": "", "<windows>": "C:\\Windows" });

	it("reduces a path to its most specific root, lower-case with forward slashes", () => {
		assert.deepEqual(normalizePath("C:\\VS\\VC\\TOOLS\\MSVC\\14.51.36231\\LIB\\X64\\LIBCMT.LIB", roots), { root: "<msvc>", path: "lib/x64/libcmt.lib" });
		assert.deepEqual(normalizePath("C:\\VS\\MSBUILD\\X.TARGETS", roots), { root: "<vs>", path: "msbuild/x.targets" });
		assert.deepEqual(normalizePath("D:\\A\\REPO\\NODE_MODULES\\NODE-GYP\\SRC\\WIN_DELAY_LOAD_HOOK.CC", roots), { root: "<node_modules>", path: "node-gyp/src/win_delay_load_hook.cc" });
		assert.deepEqual(normalizePath("D:\\A\\REPO\\NATIVE\\HWSM\\HWSM.C", roots), { root: "<repo>", path: "native/hwsm/hwsm.c" });
		assert.deepEqual(normalizePath("E:\\Users\\someone\\private\\thing.h", roots), { root: "<other>", path: "thing.h" }, "no machine path outside the roots");
		assert.equal(roots.some((root) => root.token === "<nodedir>"), false, "an unknown root is left out, not matched against everything");
	});

	it("replaces root prefixes in command lines in both backslash spellings", () => {
		assert.equal(normalizeCommand("/I\"C:\\PROGRAM FILES (X86)\\WINDOWS KITS\\10\\INCLUDE\" \"D:\\\\A\\\\REPO\\\\X.LIB\" /OUT:\"D:\\A\\REPO\\NATIVE\\X.NODE\"", roots), "/I\"<kits>\\INCLUDE\" \"<repo>\\\\X.LIB\" /OUT:\"<repo>\\NATIVE\\X.NODE\"");
	});

	it("records hashed inputs, leaves repository and system files out, and digests deterministically", () => {
		const files = new Map([["C:\\PROGRAM FILES (X86)\\WINDOWS KITS\\10\\LIB\\UM\\X64\\KERNEL32.LIB", Buffer.from("kernel32 v1")], ["C:\\VS\\VC\\TOOLS\\MSVC\\14.51.36231\\LIB\\X64\\LIBCMT.LIB", Buffer.from("libcmt")]]);
		const tlogs = {
			clRead: utf16("^D:\\A\\REPO\\NATIVE\\HWSM\\HWSM.C\r\nC:\\WINDOWS\\GLOBALIZATION\\SORTING\\SORTDEFAULT.NLS\r\nD:\\A\\REPO\\NATIVE\\HWSM\\HWSM-VERSION.H\r\n"),
			linkRead: utf16("^D:\\A\\REPO\\X.OBJ\r\nC:\\PROGRAM FILES (X86)\\WINDOWS KITS\\10\\LIB\\UM\\X64\\KERNEL32.LIB\r\nC:\\VS\\VC\\TOOLS\\MSVC\\14.51.36231\\LIB\\X64\\LIBCMT.LIB\r\nD:\\A\\REPO\\NATIVE\\HWSM\\BUILD\\RELEASE\\OBJ\\HWSM\\HWSM.OBJ\r\nC:\\GONE\\MISSING.LIB\r\n"),
			rcRead: null,
			clCommand: utf16("^D:\\A\\REPO\\NATIVE\\HWSM\\HWSM.C\r\n/c /W4 /WX D:\\A\\REPO\\NATIVE\\HWSM\\HWSM.C\r\n"),
			linkCommand: utf16("^D:\\A\\REPO\\X.OBJ\r\n/OUT:\"D:\\A\\REPO\\X.NODE\"\r\n"),
			rcCommand: null
		};
		const record = binaryInputs({ tlogs, roots, readFile: (file) => files.get(file) ?? null });
		assert.deepEqual(record.inputs.map((input) => `${input.root}/${input.path}`), ["<kits>/lib/um/x64/kernel32.lib", "<msvc>/lib/x64/libcmt.lib", "<other>/missing.lib"]);
		assert.equal(record.inputs[0].sha256, sha256(Buffer.from("kernel32 v1")));
		assert.equal(record.inputs[2].sha256, null, "a file gone since the build is recorded as missing, not invented");
		assert.equal(record.excluded, 3, "the locale file, the version header and the object file");
		assert.deepEqual(record.commandLines, { cl: ["/c /W4 /WX <repo>\\NATIVE\\HWSM\\HWSM.C"], link: ["/OUT:\"<repo>\\X.NODE\""], rc: [] });
		const shared = { tools: [{ root: "<msvc>", path: "bin/hostx64/x64/link.exe", sha256: "1".repeat(64) }], nodeHeaders: { version: "20.20.0", headersDigest: "h", nodeLibSha256: "n", commonGypiSha256: "c" }, nodeGyp: { version: "12.4.0", addonGypiSha256: "a", delayLoadHookSha256: "d" }, env: { CL: null, _CL_: null, LINK: null, _LINK_: null } };
		const digest = inputsDigestOf(record, shared);
		assert.equal(inputsDigestOf({ ...record, inputs: [...record.inputs].reverse() }, shared), digest, "order does not matter");
		files.set("C:\\PROGRAM FILES (X86)\\WINDOWS KITS\\10\\LIB\\UM\\X64\\KERNEL32.LIB", Buffer.from("kernel32 v2"));
		assert.notEqual(inputsDigestOf(binaryInputs({ tlogs, roots, readFile: (file) => files.get(file) ?? null }), shared), digest, "a moved kernel32.lib moves the digest");
		assert.notEqual(inputsDigestOf(record, { ...shared, env: { ...shared.env, LINK: "/LIBPATH:x" } }), digest, "a LINK variable moves the digest");
		assert.equal(digestLines(["b", "a"]), digestLines(["a", "b"]));
	});
});

/** A build tree the way node-gyp and MSBuild leave it, for the binaries named. */
function fakeBuild(root, { binaries = NATIVE_BINARIES, state = "PlatformToolSet=v143:VCToolArchitecture=Native64Bit:VCToolsVersion=14.51.36231:TargetPlatformVersion=10.0.26100.0:" } = {}) {
	const vs = path.join(root, "Microsoft Visual Studio", "18", "Enterprise");
	const msvc = path.join(vs, "VC", "Tools", "MSVC", "14.51.36231");
	const kits = path.join(root, "Windows Kits", "10");
	const nodedir = path.join(root, "node-gyp-cache", "20.20.0");
	const put = (file, content) => {
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.writeFileSync(file, content);
	};
	const version = Buffer.alloc(64);
	version.writeUInt32LE(0xfeef04bd, 16);
	version.writeUInt32LE((19 << 16) | 51, 24);
	version.writeUInt32LE((36260 << 16) >>> 0, 28);
	put(path.join(msvc, "bin", "Hostx64", "x64", "cl.exe"), version);
	put(path.join(msvc, "bin", "Hostx64", "x64", "link.exe"), Buffer.from("link"));
	put(path.join(msvc, "lib", "x64", "libcmt.lib"), "libcmt");
	put(path.join(kits, "Lib", "10.0.26100.0", "um", "x64", "kernel32.lib"), "kernel32");
	put(path.join(kits, "bin", "10.0.26100.0", "x64", "rc.exe"), "rc");
	put(path.join(nodedir, "include", "node", "node_version.h"), "#define NODE_MAJOR_VERSION 20\n#define NODE_MINOR_VERSION 20\n#define NODE_PATCH_VERSION 0\n");
	put(path.join(nodedir, "include", "node", "common.gypi"), "{}");
	put(path.join(nodedir, "x64", "node.lib"), "node.lib");
	put(path.join(root, "repo", "node_modules", "node-gyp", "package.json"), JSON.stringify({ version: "12.4.0" }));
	put(path.join(root, "repo", "node_modules", "node-gyp", "addon.gypi"), "{}");
	for (const binary of binaries) {
		const build = path.join(root, "repo", ...binary.dir.split("/"), "build");
		const tlog = path.join(build, "Release", "obj", binary.target, `${binary.target}.tlog`);
		put(path.join(build, "config.gypi"), `{ "variables": { "nodedir": ${JSON.stringify(nodedir)} } }`);
		put(path.join(tlog, `${binary.target}.lastbuildstate`), `${state}\r\nRelease|x64|${build}\\|\r\n`);
		put(path.join(tlog, "CL.read.1.tlog"), utf16(`^${path.join(root, "repo", binary.dir, `${binary.target}.c`).toUpperCase()}\r\n${path.join(kits, "Include", "10.0.26100.0", "um", "windows.h").toUpperCase()}\r\n`));
		put(path.join(tlog, "link.read.1.tlog"), utf16(`^X\r\n${path.join(kits, "Lib", "10.0.26100.0", "um", "x64", "kernel32.lib").toUpperCase()}\r\n${path.join(msvc, "lib", "x64", "libcmt.lib").toUpperCase()}\r\n`));
		put(path.join(tlog, "link.command.1.tlog"), utf16(`^X\r\n/OUT:"${path.join(root, "repo", binary.dir, "build", "Release", binary.file).toUpperCase()}" "${path.join(nodedir, "x64", "node.lib").toUpperCase().replaceAll("\\", "\\\\")}"\r\n`));
	}
	return { repo: path.join(root, "repo"), vs };
}

describe("toolchain record of a build tree", () => {
	it("collects versions, hashes and per-binary inputs with no machine path in the record", () => {
		const root = fs.mkdtempSync(path.join(scratch, "tree-"));
		const { repo, vs } = fakeBuild(root);
		const record = collectToolchain({ repoRoot: repo, binaries: NATIVE_BINARIES, env: { SystemRoot: "C:\\Windows", ImageOS: "win25", ImageVersion: "20261021.278.1", LINK: "/LIBPATH:x" }, readRegistry: () => "    DisplayName    REG_SZ    Windows Software Development Kit - Windows 10.0.26100.7705\r\n", vswhere: () => [{ installationPath: vs, installationVersion: "18.11.12315.225", displayName: "Visual Studio Enterprise 2026", catalog: { productDisplayVersion: "18.11.0" } }] });
		assert.deepEqual(record.runnerImage, { os: "win25", version: "20261021.278.1" });
		assert.deepEqual(record.vsInstance, { version: "18.11.12315.225", displayName: "Visual Studio Enterprise 2026", productDisplayVersion: "18.11.0" });
		assert.deepEqual(record.msvc, { toolset: "v143", toolsVersion: "14.51.36231", toolArchitecture: "Native64Bit", clFileVersion: "19.51.36260.0", linkFileVersion: null });
		assert.deepEqual(record.windowsSdk, { targetPlatformVersion: "10.0.26100.0", servicingVersion: "10.0.26100.7705", source: "uninstall registration" });
		assert.equal(record.nodeHeaders.version, "20.20.0");
		assert.equal(record.nodeHeaders.nodeLibSha256, sha256(Buffer.from("node.lib")));
		assert.equal(record.nodeGyp.version, "12.4.0");
		assert.equal(record.env.LINK, "/LIBPATH:x");
		assert.deepEqual(record.tools.map((tool) => `${tool.root}/${tool.path}`), ["<msvc>/bin/hostx64/x64/cl.exe", "<msvc>/bin/hostx64/x64/link.exe", "<kits>/bin/10.0.26100.0/x64/rc.exe"]);
		assert.deepEqual(Object.keys(record.binaries), ["hwsm.node"]);
		for (const binary of Object.values(record.binaries)) {
			assert.deepEqual(binary.inputs.map((input) => `${input.root}/${input.path}`), ["<kits>/include/10.0.26100.0/um/windows.h", "<kits>/lib/10.0.26100.0/um/x64/kernel32.lib", "<msvc>/lib/x64/libcmt.lib"]);
			assert.match(binary.commandLines.link[0], /^\/OUT:"<repo>\\NATIVE\\HWSM\\BUILD\\RELEASE\\HWSM\.NODE" "<nodedir>\\\\X64\\\\NODE\.LIB"$/);
			assert.match(binary.inputsDigest, /^[0-9a-f]{64}$/);
		}
		const text = JSON.stringify(record).toUpperCase();
		for (const leak of [root, root.replaceAll("\\", "\\\\")]) assert.equal(text.includes(leak.toUpperCase()), false, "no scratch path in the record");
		const again = collectToolchain({ repoRoot: repo, binaries: NATIVE_BINARIES, env: { SystemRoot: "C:\\Windows", ImageOS: "win25", ImageVersion: "20261021.278.1", LINK: "/LIBPATH:x" }, readRegistry: () => "", vswhere: () => [] });
		assert.equal(again.inputsDigest, record.inputsDigest, "the digest does not depend on vswhere or the registry, only on what went into the build");
	});

	it("refuses a tree without build logs and binaries built by different toolsets", () => {
		const empty = fs.mkdtempSync(path.join(scratch, "empty-"));
		assert.throws(() => collectToolchain({ repoRoot: empty, binaries: NATIVE_BINARIES, readRegistry: () => "", vswhere: () => [] }), /no MSBuild build state .* run `npm run build:native`/);
		const root = fs.mkdtempSync(path.join(scratch, "mixed-"));
		// A second binary beside hwsm, built by an older toolset.
		const second = { ...NATIVE_BINARIES[0], file: "second.node", target: "second", dir: "native/second" };
		const { repo } = fakeBuild(root);
		fakeBuild(root, { binaries: [second], state: "PlatformToolSet=v143:VCToolArchitecture=Native64Bit:VCToolsVersion=14.44.35207:TargetPlatformVersion=10.0.26100.0:" });
		assert.throws(() => collectToolchain({ repoRoot: repo, binaries: [...NATIVE_BINARIES, second], readRegistry: () => "", vswhere: () => [] }), /rebuild every binary with one `npm run build:native`/);
	});
});

describe("toolchain policy", () => {
	it("is reviewed, record-only for this release, and pins every field it can", () => {
		const policy = JSON.parse(fs.readFileSync(path.join(ROOT, "native", "toolchain-policy.json"), "utf8"));
		assert.equal(policy.mode, "record-only");
		assert.match(policy.reviewed, /^\d{4}-\d{2}-\d{2}$/);
		for (const field of POLICY_FIELD_NAMES) assert.ok(field in policy, field);
		assert.equal(policy.nodeHeaders, "20.20.0");
		assert.match(policy.nodeLibSha256, /^[0-9a-f]{64}$/);
		const text = JSON.stringify(policy);
		assert.doesNotMatch(text, /\u2014/, "no em dashes");
	});

	it("reports mismatches, unpinned fields and the policy that would describe the record", () => {
		const record = { msvc: { toolsVersion: "14.44.35207", clFileVersion: "19.44.35228.0", linkFileVersion: "14.44.35228.0" }, windowsSdk: { targetPlatformVersion: "10.0.26100.0", servicingVersion: "10.0.26100.7705" }, nodeHeaders: { version: "20.20.0", nodeLibSha256: "n" }, nodeGyp: { version: "12.4.0" } };
		const result = comparePolicy(record, { msvcToolsVersion: "14.51.36231", clVersion: "19.51.36260", linkVersion: null, windowsSdkTargetPlatform: "10.0.26100.0", windowsSdkServicing: null, nodeHeaders: "20.20.0", nodeLibSha256: "n", nodeGyp: "12.4.0" });
		assert.deepEqual(result.mismatches, [{ field: "msvcToolsVersion", expected: "14.51.36231", actual: "14.44.35207" }, { field: "clVersion", expected: "19.51.36260", actual: "19.44.35228" }]);
		assert.deepEqual(result.unpinned, ["linkVersion", "windowsSdkServicing"]);
		assert.deepEqual(result.suggested, { msvcToolsVersion: "14.44.35207", clVersion: "19.44.35228", linkVersion: "14.44.35228", windowsSdkTargetPlatform: "10.0.26100.0", windowsSdkServicing: "10.0.26100.7705", nodeHeaders: "20.20.0", nodeLibSha256: "n", nodeGyp: "12.4.0" });
		assert.deepEqual(comparePolicy(record, result.suggested).mismatches, []);
	});
});
